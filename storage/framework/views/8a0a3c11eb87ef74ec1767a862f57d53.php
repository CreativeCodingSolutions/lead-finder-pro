            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Säule 1: Automatisierte Lead-Recherche</h3>
            <p>Stunden manuelles Googlen gehört der Vergangenheit an. Moderne Tools ermöglichen es, Hunderte qualifizierte Leads in Minuten zu finden:</p>
            <ul class="list-disc list-inside space-y-2 mt-2">
                <li><strong>Branchen-Filter:</strong> Nur Unternehmen aus relevanten Branchen</li>
                <li><strong>Standort-Filter:</strong> DACH-Region, spezifische Städte oder Radius</li>
                <li><strong>Technologie-Check:</strong> Welche Website-Technologie nutzen sie?</li>
                <li><strong>Größen-Filter:</strong> Mitarbeiterzahl, Umsatz, Bewertungen</li>
                <li><strong>Trigger-Events:</strong> Neue Website, Funding, Expansion</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Säule 2: Personalisierung auf Knopfdruck</h3>
            <p>Automation bedeutet nicht "impersonal". Im Gegenteil: Mit den richtigen Daten wird Personalisierung einfacher:</p>
            <ul class="list-disc list-inside space-y-2 mt-2">
                <li><strong>Website-Analyse:</strong> Automatisch erkennen, was auf der Website fehlt</li>
                <li><strong>Branchen-Templates:</strong> Vorgefertigte Texte pro Branche</li>
                <li><strong>Dynamische Felder:</strong> Firmenname, Stadt, spezifische Beobachtung</li>
                <li><strong>Social Proof:</strong> Referenzen aus derselben Branche einbinden</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Säule 3: Multi-Channel Outreach</h3>
            <p>E-Mail allein reicht nicht mehr. Die besten Ergebnisse erzielt man durch Kombination:</p>
            <ul class="list-disc list-inside space-y-2 mt-2">
                <li><strong>E-Mail:</strong> Primärer Kanal, personalisiert, 3-5 Sequenz-Schritte</li>
                <li><strong>LinkedIn:</strong> Connection Request + Nachricht nach Annahme</li>
                <li><strong>Telefon:</stron> Für warme Leads nach E-Mail-Öffnung</li>
                <li><strong>Retargeting:</strong> LinkedIn Ads für geöffnete aber nicht geantwortete Mails</li>
            </ul>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Säule 4: Follow-Up-Automation</h3>
            <p>80% der Deals brauchen mindestens 5 Kontaktversuche. Automatisierung stellt sicher, dass kein Lead durch fällt:</p>
            <ul class="list-disc list-inside space-y-2 mt-2">
                <li><strong>Tag 3:</strong> Kurze Erinnerung mit Social Proof</li>
                <li><strong>Tag 7:</strong> Wert-Content (Case Study, Statistik)</li>
                <li><strong>Tag 14:</strong> Letzte Information mit Dringlichkeit</li>
                <li><strong>Tag 30:</strong> Break-up Mail ("Soll ich Sie aus der Liste nehmen?")</li>
            </ul>

