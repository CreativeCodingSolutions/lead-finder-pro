            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">Warum Leads nicht konvertieren</h2>

            <p>Die häufigsten Gründe, warum lokale Leads nicht zu Kunden werden:</p>

            <div class="space-y-4 my-6">
                <div class="border-l-4 border-red-400 pl-4">
                    <p class="font-semibold text-gray-900">1. Kein Vertrauensaufbau vor dem Pitch</p>
                    <p class="text-gray-600 text-sm">78% der Entscheider antworten nicht auf kalte Kontaktanfragen, wenn sie den Absender nicht kennen.</p>
                </div>
                <div class="border-l-4 border-red-400 pl-4">
                    <p class="font-semibold text-gray-900">2. Zu generische Ansprache</p>
                    <p class="text-gray-600 text-sm">„Sehr geehrte Damen und Herren" funktioniert 2026 nicht mehr. Personalisierung erhöht die Antwortquote um 3-5x.</p>
                </div>
                <div class="border-l-4 border-red-400 pl-4">
                    <p class="font-semibold text-gray-900">3. Kein Follow-up</p>
                    <p class="text-gray-600 text-sm">80% der Verkäufe erfordern mindestens 5 Follow-ups. Die meisten geben nach dem ersten Versuch auf.</p>
                </div>
                <div class="border-l-4 border-red-400 pl-4">
                    <p class="font-semibold text-gray-900">4. Fehlender Mehrwert</p>
                    <p class="text-gray-600 text-sm">„Nutzen Sie unser Angebot" statt „Hier ist, wie wir Ihnen helfen können" — der Unterschied ist entscheidend.</p>
