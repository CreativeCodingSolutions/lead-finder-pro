            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">5 Strategien zur Conversion-Optimierung</h2>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Strategie 1: Recherchieren bevor Sie schreiben</h3>

            <p>Bevor Sie eine E-Mail verfassen, investieren Sie 2-3 Minuten pro Lead:</p>
            <ul class="list-disc list-inside space-y-2 mt-2">
                <li><strong>Website des Leads besuchen:</strong> Was sind ihre Leistungen? Was sind ihre Schmerzpunkte?</li>
                <li><strong>Google-Bewertungen lesen:</strong> Was beanstanden Kunden? Hier liegt Ihr Einstiegspunkt.</li>
                <li><strong>Social Media checken:</strong> LinkedIn, Facebook — was teilen sie? Wann wurden sie zuletzt aktiv?</li>
                <li><strong>Wettbewerber analysieren:</strong> Wer sind ihre aktuellen Lieferanten? Was können Sie besser machen?</li>
            </ul>

            <p class="mt-4">Mit LeadFinderPro erhalten Sie bereits Basisdaten: Name, Adresse, Telefon, Website. Nutzen Sie diese als Ausgangspunkt für Ihre Individualrecherche.</p>

            <h3 class="text-xl font-semibold text-gray-900 mt-8 mb-3">Strategie 2: Die erste E-Mail richtig schreiben</h3>

            <p>Die optimale Outreach-E-Mail für lokale Dienstleister folgt dieser Struktur:</p>

            <div class="bg-gray-50 border border-gray-200 rounded-lg p-4 my-6 font-mono text-sm">
                <p class="text-gray-600"><strong>Betreff:</strong> [Name], eine Idee zu [konkretes Problem]</p>
                <p class="text-gray-600 mt-3"><strong>Text:</strong></p>
                <p class="text-gray-600">Hallo [Vorname],</p>
                <p class="text-gray-600">Ich habe [Firmenname] auf [Quelle, z.B. Google Maps] gefunden und [persönlicher Bezug, z.B. „Ihre Bewertungen über Behandlung X"].</p>
                <p class="text-gray-600 mt-2">Wir helfen lokalen [Branche] dabei, [konkretes Ergebnis, z.B. „30% mehr Online-Terminbuchungen zu generieren"].</p>
                <p class="text-gray-600 mt-2">Passt ein kurzer Austausch nächste Woche für Sie? Bitte einfach mit Terminvorschlag antworten.</p>
                <p class="text-gray-600 mt-2">Viele Grüße,<br>[Ihr Name]</p>
            </div>

