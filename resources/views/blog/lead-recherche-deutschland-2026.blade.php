            <h2 class="text-2xl font-bold text-gray-900 mt-12 mb-4">DSGVO und B2B Lead-Recherche: Was ist erlaubt?</h2>

            <p>Die häufigste Frage unserer Nutzer: <strong>„Darf ich diese Unternehmenskontakte für Kaltakquise nutzen?"</strong></p>

            <p><strong>Kurze Antwort:</strong> Ja, unter bestimmten Voraussetzungen.</p>

            <p><strong>Rechtliche Basis (DACH-Raum):</strong></p>
            <ul class="list-disc list-inside space-y-1 mt-2">
                <li>✅ <strong>§7 UWG (Deutschland):</strong> B2B-Kaltakquise per E-Mail ist erlaubt bei berechtigtem Interesse (Art 6 DSGVO)</li>
                <li>✅ <strong>Art 6 Abs 1 lit f DSGVO:</strong> Berechtigtes Interesse des Unternehmens an der Kontaktaufnahme besteht</li>
                <li>⚠️ <strong>Österreich/UWG §107:</strong> Strengere Regeln — vorherige Kontaktaufnahme empfohlen</li>
                <li>⚠️ <strong>Schweiz/UWG Art 3:</strong> Opt-Out-Pflicht — Abmeldemöglichkeit in jeder Mail einbauen</li>
            </ul>

            <p><strong>Best Practices für DSGVO-konforme Recherche:</strong></p>
            <ol class="list-decimal list-inside space-y-1 mt-2">
                <li>Datenquelle dokumentieren (OSM = öffentliche, gepflegte Quelle)</li>
                <li>Berechtigtes Interesse schlüssig argumentieren und dokumentieren</li>
                <li>Impressum in jeder Outreach-Mail</li>
                <li>Ein-Klick-Abmeldemöglichkeit anbieten</li>
                <li>Keine Daten an unberechtigte Dritte weitergeben</li>
            </ol>

